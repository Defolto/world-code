// Размеры клетки — общие для демки на главной и для игры.
//
// CELL — внутренние единицы viewBox, в них считает всё, что рисует SVG.
// DISPLAY_CELL — сколько CSS-пикселей клетка занимает на экране при
// естественном размере (решение из generatsiya-grafiki.md: 80px). Сцена
// масштабируется целиком, так что 80 — номинал, а не жёсткий размер.
export const CELL = 44;
export const DISPLAY_CELL = 80;

// Кольцо скалы вокруг карты, в клетках: за краем карты стена не только
// для правил, но и на экране — подземелье вырублено в камне, а не
// висит в пустоте. Сцена шире карты на 2·PAD клеток, содержимое сдвинуто
// на PAD; координаты героя и клеток от этого не меняются
export const PAD = 2;

/** Ключ ворот в DOM (data-gate) и в плеере: одна функция, чтобы не разъехались */
export const gateKey = (x: number, y: number) => `${x}-${y}`;
